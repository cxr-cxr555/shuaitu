function buildDefaultHeroes() {
  const heroes = [];
  for (const roster of ROSTER_SOURCES) {
    roster.entries.forEach(([name, faction], index) => {
      heroes.push({
        id: `hero-${roster.groupId}-${String(index + 1).padStart(3, '0')}`,
        name,
        faction,
        rosterGroup: roster.groupId,
        score: null,
      });
    });
  }
  return heroes;
}

